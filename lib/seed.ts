const day = (
  id: string,
  weekday: string,
  neighborhood: string,
  theme: string,
  description: string,
  emoji: string,
  window: string,
  stops: [string, number][],
): DayPlan => ({
  id,
  date: '2027-01-0' + id,
  weekday,
  neighborhood,
  theme,
  description,
  emoji,
  window,
  entries: stops.map(
    ([placeId, duration]) =>
      ({
        id: id + '-' + placeId,
        placeId,
        dayId: id,
        mode: 'Anytime',
        start: '',
        end: '',
        duration,
        priority: 'Must visit',
        reservation: '',
        status: 'Planned',
        notes: '',
      }) satisfies AgendaEntry,
  ),
})
